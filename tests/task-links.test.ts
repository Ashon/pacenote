describe("the sessions' logs", () => {
  it('keep what tells whose work a session was: its folder, branches, what you typed and the tasks it named', async () => {
    const home = dir('read-home')
    const project = dir('read-home', '.claude', 'projects', '-w-payments')
    writeFileSync(
      path.join(project, 'c1.jsonl'),
      jsonl(
        { type: 'summary', summary: 'Earlier' },
        {
          type: 'user',
          sessionId: 'c1',
          cwd: '/w/payments',
          gitBranch: 'main',
          timestamp: POSTED,
          message: { role: 'user', content: 'Look at the retry timeouts' },
        },
        {
          type: 'user',
          isMeta: true,
          sessionId: 'c1',
          gitBranch: 'main',
          message: { role: 'user', content: 'Caveat: generated by a command' },
        },
        {
          type: 'assistant',
          sessionId: 'c1',
          gitBranch: 'fix/retry',
          timestamp: LATER,
          message: {
            role: 'assistant',
            content: [
              { type: 'text', text: 'On it.' },
              {
                type: 'tool_use',
                name: 'mcp__pacenote__close_task',
                input: { task: 'C1:1.000100' },
              },
            ],
          },
        },
        {
          type: 'user',
          sessionId: 'c1',
          gitBranch: 'fix/retry',
          message: {
            role: 'user',
            content: [{ type: 'tool_result', content: 'archives/C1/p1000200' }],
          },
        },
        {
          type: 'user',
          sessionId: 'c1',
          gitBranch: 'fix/retry',
          timestamp: LATER,
          message: {
            role: 'user',
            content: [{ type: 'text', text: 'Now the backoff' }],
          },
        }
      )
    )
    // A subagent keeps its own log, apart from its session's
    writeFileSync(
      path.join(
        dir(
          'read-home',
          '.claude',
          'projects',
          '-w-payments',
          'c1',
          'subagents'
        ),
        'a.jsonl'
      ),
      jsonl({ type: 'user', sessionId: 'sub', cwd: '/w/payments' })
    )
    const codex = dir('read-home', '.codex', 'sessions', '2026', '10', '13')
    writeFileSync(
      path.join(codex, 'rollout-2026-10-13T10-00-00-x1.jsonl'),
      jsonl(
        {
          timestamp: POSTED,
          type: 'session_meta',
          payload: {
            id: 'x1',
            cwd: '/w/payments',
            git: { branch: 'feat/webhooks' },
          },
        },
        {
          timestamp: POSTED,
          type: 'response_item',
          payload: {
            type: 'message',
            role: 'user',
            content: [
              {
                type: 'input_text',
                text: '<environment_context>/w</environment_context>',
              },
            ],
          },
        },
        {
          timestamp: LATER,
          type: 'response_item',
          payload: {
            type: 'message',
            role: 'user',
            content: [{ type: 'input_text', text: 'Retry webhooks 5 times' }],
          },
        },
        {
          timestamp: LATER,
          type: 'response_item',
          payload: {
            type: 'function_call',
            name: 'mcp__pacenote__task_context',
            arguments: JSON.stringify({ task: 'C1:2.000100' }),
          },
        }
      )
    )
    const index = new SessionIndex({ home })
    await index.refresh(NOW)
    expect(index.sessions()).toHaveLength(2)
    expect(index.session('c1')).toMatchObject({
      tool: 'claude',
      cwd: '/w/payments',
      startedAt: POSTED,
      branches: ['main', 'fix/retry'],
      branch: 'fix/retry',
      prompts: [
        { at: POSTED, text: 'Look at the retry timeouts' },
        { at: LATER, text: 'Now the backoff' },
      ],
      taskRefs: ['C1:1.000100'],
    })
    expect(index.session('x1')).toMatchObject({
      tool: 'codex',
      cwd: '/w/payments',
      branches: ['feat/webhooks'],
      prompts: [{ at: LATER, text: 'Retry webhooks 5 times' }],
      taskRefs: ['C1:2.000100'],
    })
  })

  it('reads a log from where it was left as it grows, a line once it ends, and a log cut shorter again', async () => {
    const home = dir('grow-home')
    const file = path.join(
      dir('grow-home', '.claude', 'projects', '-w-payments'),
      'g1.jsonl'
    )
    const line = (text: string, gitBranch = 'main') => ({
      type: 'user',
      sessionId: 'g1',
      cwd: '/w/payments',
      gitBranch,
      timestamp: LATER,
      message: { role: 'user', content: text },
    })
    writeFileSync(file, jsonl(line('first')))
    const index = new SessionIndex({ home })
    await index.refresh(NOW)
    expect(index.session('g1')?.prompts.map((p) => p.text)).toEqual(['first'])

    // A line still being written waits until it ends.
    const next = JSON.stringify(line('second', 'fix/retry'))
    appendFileSync(file, next.slice(0, 20))
    await index.refresh(NOW)
    expect(index.session('g1')?.prompts).toHaveLength(1)
    appendFileSync(file, `${next.slice(20)}\n`)
    await index.refresh(NOW)
    expect(index.session('g1')).toMatchObject({
      branches: ['main', 'fix/retry'],
      prompts: [{ text: 'first' }, { text: 'second' }],
    })

    truncateSync(file, 0)
    writeFileSync(file, jsonl(line('again')))
    await index.refresh(NOW)
    expect(index.session('g1')?.prompts.map((p) => p.text)).toEqual(['again'])

    // Older than two weeks: left out
    const old = (NOW - 15 * 86_400_000) / 1000
    utimesSync(file, old, old)
    await index.refresh(NOW)
    expect(index.session('g1')).toBeUndefined()
  })
})

describe("which sessions were a task's work", () => {
  const retry = taskOf('C1:1.000100', {
    message: '1.000100',
    repo: 'Ashon/payments',
    action: 'code',
    summary: 'mina wants a review of PR #482 before Thursday.',
  })
  const webhooks = taskOf('C1:2.000100', {
    message: '2.000100',
    title: 'Raise the webhook retry limit',
    summary: 'hyun asked for `max_attempts` to be 5.',
  })
  const repos = new Map<string, RepoOf | undefined>([
    ['/w/payments', PAYMENTS],
    ['/w/payments-wt', PAYMENTS],
    ['/w/other', { id: '/w/other/.git', name: 'Ashon/other' }],
  ])

  it('links a session that named the task to Pacenote, or whose prompt has its Slack link', () => {
    const { found } = linkSessions({
      tasks: [retry, webhooks],
      work: work(),
      sessions: [
        summaryOf('by-id', { taskRefs: [retry.id] }),
        summaryOf('by-link', { taskRefs: [webhooks.source.permalink!] }),
        summaryOf('typed', {
          cwd: '/Users/me',
          prompts: [
            {
              text: `See https://acme.slack.com/archives/C1/p2000100?thread_ts=1.0 and ${retry.source.permalink}`,
            },
          ],
        }),
        summaryOf('nothing', { prompts: [{ text: 'Something else' }] }),
      ],
      repos,
    })
    expect(found.map((e) => [e.session, e.task, e.foundBy, e.found])).toEqual([
      ['by-id', retry.id, 'tools', true],
      ['by-link', webhooks.id, 'tools', true],
      // The link it has first
      ['typed', webhooks.id, 'link', true],
    ])
  })

  it('takes a link to a thread only when one task is in it', () => {
    const inThread = (id: string, message: string) =>
      taskOf(id, { message, thread: '5.000100' })
    const thread = 'https://acme.slack.com/archives/C1/p5000100'
    const session = summaryOf('thread', { prompts: [{ text: thread }] })
    expect(
      linkSessions({
        tasks: [inThread('C1:5.1', '5.100000')],
        work: work(),
        sessions: [session],
        repos,
      }).found.map((e) => e.task)
    ).toEqual(['C1:5.1'])
    expect(
      linkSessions({
        tasks: [inThread('C1:5.1', '5.100000'), inThread('C1:5.2', '5.200000')],
        work: work(),
        sessions: [session],
        repos,
      }).found
    ).toEqual([])
  })

  it("follows the task's branch to the sessions that went on with it, in its repository", () => {
    const { found } = linkSessions({
      tasks: [retry, webhooks],
      work: work({
        // The session Pacenote opened worked on fix/retry, after main.
        entries: [opened(retry.id, 'opened')],
      }),
      sessions: [
        summaryOf('opened', { branches: ['main', 'fix/retry'] }),
        // After /clear, in a worktree: the same repository, the same branch
        summaryOf('cleared', {
          cwd: '/w/payments-wt',
          branches: ['fix/retry', 'fix/other'],
        }),
        // On main only, or the same branch name in another repository
        summaryOf('main', { branches: ['main'] }),
        summaryOf('elsewhere', { cwd: '/w/other', branches: ['fix/retry'] }),
        // A branch the cleared session went on to lends nothing.
        summaryOf('other', { branches: ['fix/other'] }),
      ],
      repos,
    })
    expect(found.map((e) => [e.session, e.foundBy, e.branch])).toEqual([
      ['cleared', 'branch', 'fix/retry'],
    ])
  })

  it('links no session by a branch two tasks share, nor one you said is not the task’s', () => {
    const sessions = [
      summaryOf('a', { branches: ['fix/both'], taskRefs: [retry.id] }),
      summaryOf('b', { branches: ['fix/both'], taskRefs: [webhooks.id] }),
      summaryOf('c', { branches: ['fix/both'] }),
    ]
    expect(
      linkSessions({
        tasks: [retry, webhooks],
        work: work(),
        sessions,
        repos,
      }).found.map((e) => e.session)
    ).toEqual(['a', 'b'])
    expect(
      linkSessions({
        tasks: [retry],
        work: work({ notIt: [{ task: retry.id, session: 'a', at: LATER }] }),
        sessions: [summaryOf('a', { taskRefs: [retry.id] })],
        repos,
      }).found
    ).toEqual([])
  })

  it('suggests a session in the task’s repository that shares its words, after it was posted', () => {
    const typed = (text: string, at = LATER) => [{ text, at }]
    const { found, suggested } = linkSessions({
      tasks: [retry, webhooks],
      work: work(),
      sessions: [
        summaryOf('pr', {
          branch: 'review/482',
          prompts: typed('Review pull 482, the payment retry change'),
        }),
        // Words alone, not enough of them
        summaryOf('thin', { prompts: typed('Fix the payment form') }),
        // Before the task was posted
        summaryOf('before', {
          lastAt: '2026-10-12T00:00:00.000Z',
          prompts: typed('#482 payment retry', '2026-10-12T00:00:00.000Z'),
        }),
        // Another repository
        summaryOf('other', {
          cwd: '/w/other',
          prompts: typed('#482 payment retry'),
        }),
        // A task without a repository needs what only it has.
        summaryOf('code', {
          cwd: '/Users/me/scratch',
          prompts: typed('set max_attempts for the webhook retry'),
        }),
        summaryOf('words', {
          cwd: '/Users/me/scratch',
          prompts: typed('the webhook retry limit'),
        }),
      ],
      repos,
    })
    expect(found).toEqual([])
    expect(
      suggested.map((s) => [s.session, s.task, s.shares, s.branch])
    ).toEqual([
      // The likelier first
      ['code', webhooks.id, ['max_attempts', 'webhook', 'retry'], undefined],
      ['pr', retry.id, ['#482', 'payment', 'retry'], 'review/482'],
    ])
  })

  it('suggests a couple per task, not one already waiting or turned down', () => {
    const sessions = ['s1', 's2', 's3', 's4'].map((id) =>
      summaryOf(id, { prompts: [{ text: 'PR #482 payment retry', at: LATER }] })
    )
    const waiting = {
      id: 'w',
      kind: 'session' as const,
      task: retry.id,
      tool: 'claude' as const,
      session: 's1',
      cwd: '/w/payments',
      startedAt: LATER,
      shares: ['#482'],
    }
    const { suggested } = linkSessions({
      tasks: [retry],
      work: work({
        suggested: [waiting],
        notIt: [{ task: retry.id, session: 's2', at: LATER }],
      }),
      sessions,
      repos,
    })
    expect(suggested.map((s) => s.session)).toEqual(['s3'])
  })

  it('knows the session it opened in Codex by the marker in its first prompt', () => {
    const { opened: known, found } = linkSessions({
      tasks: [retry],
      work: work({
        entries: [opened(retry.id, undefined, { id: 'm1', tool: 'codex' })],
      }),
      sessions: [
        summaryOf('x9', {
          tool: 'codex',
          prompts: [
            {
              text: `You are taking over a task from Pacenote [pacenote-task:m1]. Link: ${retry.source.permalink}`,
            },
          ],
        }),
      ],
      repos,
    })
    expect(known).toEqual([{ entry: 'm1', session: 'x9' }])
    expect(found).toEqual([])
  })
})

describe('answering a suggestion', () => {
  it('links it to the task, or keeps it from being asked again', () => {
    const data = dir('answer-data')
    const suggestion = (id: string, session: string) => ({
      id,
      kind: 'session' as const,
      task: 'C1:1.000100',
      tool: 'claude' as const,
      session,
      cwd: '/w/payments',
      startedAt: new Date().toISOString(),
      shares: ['#482'],
    })
    changeWork(data, (file) => ({
      ...file,
      suggested: [suggestion('yes', 's1'), suggestion('no', 's2')],
    }))
    answerSuggestion(data, 'yes', true)
    answerSuggestion(data, 'no', false)
    expect(answerSuggestion(data, 'no', false)).toBeUndefined()
    const file = readWork(data)
    expect(file.suggested).toEqual([])
    expect(file.entries).toMatchObject([
      { id: 'yes', session: 's1', found: true, foundBy: 'you' },
    ])
    expect(file.entries[0]).not.toHaveProperty('shares')
    expect(file.notIt).toMatchObject([{ task: 'C1:1.000100', session: 's2' }])
  })
})

describe('the work file', () => {
  it('is not written again by a change that changes nothing', () => {
    const data = dir('unchanged-data')
    const entry = {
      id: 'w1',
      kind: 'session' as const,
      task: 'C1:1.000100',
      tool: 'claude' as const,
      session: 's1',
      cwd: '/w/payments',
      startedAt: new Date().toISOString(),
    }
    changeWork(data, (file) => ({ ...file, entries: [entry] }))
    const file = path.join(data, WORK_FILE)
    const then = new Date(Date.now() - 60_000)
    utimesSync(file, then, then)
    const before = statSync(file).mtimeMs
    // A session-link pass that finds nothing new
    changeWork(data, (work) => work)
    expect(statSync(file).mtimeMs).toBe(before)
    changeWork(data, (work) => ({
      ...work,
      entries: [{ ...entry, session: 's2' }],
    }))
    expect(statSync(file).mtimeMs).toBeGreaterThan(before)
    expect(readWork(data).entries).toMatchObject([{ session: 's2' }])
  })
})

describe("a session folder's repository", () => {
  it('is one for each of its worktrees, with its name and default branch', async () => {
    const repo = dir('repos', 'payments')
    const git = (cwd: string, ...args: string[]) =>
      execFileSync('git', args, { cwd, stdio: 'pipe' })
    git(repo, 'init', '-q', '-b', 'main')
    git(repo, 'remote', 'add', 'origin', 'git@github.com:Ashon/payments.git')
    git(
      repo,
      '-c',
      'user.name=t',
      '-c',
      'user.email=t@t',
      'commit',
      '-q',
      '--allow-empty',
      '-m',
      'one'
    )
    git(
      repo,
      'symbolic-ref',
      'refs/remotes/origin/HEAD',
      'refs/remotes/origin/trunk'
    )
    const worktree = path.join(root, 'repos', 'payments-wt')
    git(repo, 'worktree', 'add', '-q', '-b', 'fix/retry', worktree)

    const lookup = new RepoLookup()
    const repos = await lookup.all([repo, worktree, root])
    const main = repos.get(repo)
    expect(main).toEqual({
      id: path.join(realpathSync(repo), '.git'),
      name: 'Ashon/payments',
      defaultBranch: 'trunk',
    })
    expect(repos.get(worktree)?.id).toBe(main?.id)
    expect(repos.get(root)).toBeUndefined()
  })

  it("counts as your work's only outside Pacenote's folder and temporary ones", () => {
    const home = dir('fold-home')
    const data = dir('fold-home', '.pacenote')
    expect(yourFolder(home, path.join(home, 'git', 'payments'), [data])).toBe(
      true
    )
    expect(yourFolder(home, data, [data])).toBe(false)
    expect(yourFolder(home, path.join(data, 'handoff'), [data])).toBe(false)
    expect(yourFolder('/Users/nobody', path.join(tmpdir(), 'x'))).toBe(false)
    expect(yourFolder('/Users/nobody', '/Users/nobody/w')).toBe(true)
  })
})
